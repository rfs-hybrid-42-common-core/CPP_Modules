#ifndef ZOMBIE_HPP
#define ZOMBIE_HPP

/* ========================================================================== */
/* INCLUDES                                                                   */
/* ========================================================================== */

/* --------------------------- Internal Libraries --------------------------- */
#include <string>

/* ========================================================================== */
/* CLASSES                                                                    */
/* ========================================================================== */

/**
 * @class Zombie
 * @brief Represents a Zombie with a specific name.
 * @details This class contains a private string attribute for the name and 
 * provides methods for the zombie to announce itself, as well as debugging 
 * messages upon creation and destruction.
 */
class Zombie
{
    private:
        /* ------------------------------------------------------------------ */
        /* PRIVATE ATTRIBUTES                                                 */
        /* ------------------------------------------------------------------ */
        std::string _name;

    public:
        /* ------------------------------------------------------------------ */
        /* CONSTRUCTORS & DESTRUCTORS                                         */
        /* ------------------------------------------------------------------ */
        Zombie(std::string const & name);
        ~Zombie(void);

        /* ------------------------------------------------------------------ */
        /* PUBLIC METHODS                                                     */
        /* ------------------------------------------------------------------ */
        void announce(void);
};

/* ========================================================================== */
/* FUNCTIONS                                                                  */
/* ========================================================================== */

Zombie* newZombie(std::string name);
void    randomChump(std::string name);

#endif
