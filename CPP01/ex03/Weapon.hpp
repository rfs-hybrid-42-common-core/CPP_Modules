#ifndef WEAPON_HPP
#define WEAPON_HPP

/* ========================================================================== */
/* INCLUDES                                                                   */
/* ========================================================================== */

/* --------------------------- Internal Libraries --------------------------- */
#include <string>

/* ========================================================================== */
/* CLASSES                                                                    */
/* ========================================================================== */

/**
 * @class Weapon
 * @brief Represents a weapon with a specific type.
 * @details Manages a single string attribute for the weapon's type, allowing 
 * it to be safely retrieved or modified by external human classes.
 */
class Weapon
{
    private:
        /* ------------------------------------------------------------------ */
        /* PRIVATE ATTRIBUTES                                                 */
        /* ------------------------------------------------------------------ */
        std::string _type;

    public:
        /* ------------------------------------------------------------------ */
        /* CONSTRUCTORS & DESTRUCTORS                                         */
        /* ------------------------------------------------------------------ */
        Weapon(std::string const & type);
        ~Weapon(void);

        /* ------------------------------------------------------------------ */
        /* GETTERS                                                            */
        /* ------------------------------------------------------------------ */
        std::string const & getType(void) const;

        /* ------------------------------------------------------------------ */
        /* SETTERS                                                            */
        /* ------------------------------------------------------------------ */
        void setType(std::string const & type);
};

#endif
