#ifndef POINT_HPP
#define POINT_HPP

/* ========================================================================== */
/* INCLUDES                                                                   */
/* ========================================================================== */

/* --------------------------- External Libraries --------------------------- */
#include "Fixed.hpp"

/* ========================================================================== */
/* CLASSES                                                                    */
/* ========================================================================== */

/**
 * @class Point
 * @brief Represents a 2D point.
 * @details Implements a 2D point in Orthodox Canonical Form using the Fixed 
 * class for its x and y coordinates.
 */
class Point
{
    private:
        /* ------------------------------------------------------------------ */
        /* PRIVATE ATTRIBUTES                                                 */
        /* ------------------------------------------------------------------ */
        Fixed const x;
        Fixed const y;

    public:
        /* ------------------------------------------------------------------ */
        /* CONSTRUCTORS & DESTRUCTORS                                         */
        /* ------------------------------------------------------------------ */
        Point(void);
        Point(float const n1, float const n2);
        Point(Point const & other);
        ~Point(void);

        /* ------------------------------------------------------------------ */
        /* OPERATOR OVERLOADS                                                 */
        /* ------------------------------------------------------------------ */
        Point& operator=(Point const & other);

        /* ------------------------------------------------------------------ */
        /* GETTERS                                                            */
        /* ------------------------------------------------------------------ */
        Fixed const & getX(void) const;
        Fixed const & getY(void) const;
};

/* ========================================================================== */
/* FUNCTIONS                                                                  */
/* ========================================================================== */

bool bsp(Point const a, Point const b, Point const c, Point const point);

#endif
