/**
 * @class Dog
 * @brief Represents a dog, derived from Animal.
 * @details Implements a Dog class in Orthodox Canonical Form that inherits 
 * from the Animal base class and overrides its virtual methods to demonstrate 
 * dynamic binding.
 */
class Dog : public Animal
{
    public:
        /* ------------------------------------------------------------------ */
        /* CONSTRUCTORS & DESTRUCTORS                                         */
        /* ------------------------------------------------------------------ */
        Dog(void);
        Dog(Dog const & other);
        virtual ~Dog(void);

        /* ------------------------------------------------------------------ */
        /* OPERATOR OVERLOADS                                                 */
        /* ------------------------------------------------------------------ */
        Dog& operator=(Dog const & other);

        /* ------------------------------------------------------------------ */
        /* PUBLIC METHODS                                                     */
        /* ------------------------------------------------------------------ */
        void makeSound(void) const;
};

