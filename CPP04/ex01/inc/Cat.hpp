#ifndef CAT_HPP
#define CAT_HPP

/* ========================================================================== */
/* INCLUDES                                                                   */
/* ========================================================================== */

/* --------------------------- External Libraries --------------------------- */
#include "Animal.hpp"
#include "Brain.hpp"

/* ========================================================================== */
/* CLASSES                                                                    */
/* ========================================================================== */

/**
 * @class Cat
 * @brief Represents a cat, derived from Animal.
 * @details Implements a Cat class in Orthodox Canonical Form that inherits 
 * from the Animal base class. Contains a dynamically allocated Brain attribute 
 * and overrides virtual methods to demonstrate dynamic binding.
 */
class Cat : public Animal
{
    private:
        /* ------------------------------------------------------------------ */
        /* PRIVATE ATTRIBUTES                                                 */
        /* ------------------------------------------------------------------ */        
        Brain *brain;
    
    public:
        /* ------------------------------------------------------------------ */
        /* CONSTRUCTORS & DESTRUCTORS                                         */
        /* ------------------------------------------------------------------ */
        Cat(void);
        Cat(Cat const & other);
        virtual ~Cat(void);

        /* ------------------------------------------------------------------ */
        /* OPERATOR OVERLOADS                                                 */
        /* ------------------------------------------------------------------ */
        Cat& operator=(Cat const & other);

        /* ------------------------------------------------------------------ */
        /* GETTERS                                                            */
        /* ------------------------------------------------------------------ */
        std::string const & getIdea(int index) const;

        /* ------------------------------------------------------------------ */
        /* SETTERS                                                            */
        /* ------------------------------------------------------------------ */
        void setIdea(int index, std::string const & idea);

        /* ------------------------------------------------------------------ */
        /* PUBLIC METHODS                                                     */
        /* ------------------------------------------------------------------ */
        void makeSound(void) const;
};

#endif
