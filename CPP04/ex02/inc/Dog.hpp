#ifndef DOG_HPP
#define DOG_HPP

/* ========================================================================== */
/* INCLUDES                                                                   */
/* ========================================================================== */

/* --------------------------- External Libraries --------------------------- */
#include "AAnimal.hpp"
#include "Brain.hpp"

/* ========================================================================== */
/* CLASSES                                                                    */
/* ========================================================================== */

/**
 * @class Dog
 * @brief Represents a dog, derived from AAnimal.
 * @details Implements a Dog class in Orthodox Canonical Form that inherits 
 * from the abstract AAnimal base class. Contains a dynamically allocated Brain 
 * attribute and overrides virtual methods to demonstrate dynamic binding.
 */
class Dog : public AAnimal
{
    private:
        /* ------------------------------------------------------------------ */
        /* PRIVATE ATTRIBUTES                                                 */
        /* ------------------------------------------------------------------ */        
        Brain *brain;

    public:
        /* ------------------------------------------------------------------ */
        /* CONSTRUCTORS & DESTRUCTORS                                         */
        /* ------------------------------------------------------------------ */
        Dog(void);
        Dog(Dog const & other);
        virtual ~Dog(void);

        /* ------------------------------------------------------------------ */
        /* OPERATOR OVERLOADS                                                 */
        /* ------------------------------------------------------------------ */
        Dog& operator=(Dog const & other);

        /* ------------------------------------------------------------------ */
        /* GETTERS                                                            */
        /* ------------------------------------------------------------------ */
        std::string const & getIdea(int index) const;

        /* ------------------------------------------------------------------ */
        /* SETTERS                                                            */
        /* ------------------------------------------------------------------ */
        void setIdea(int index, std::string const & idea);

        /* ------------------------------------------------------------------ */
        /* PUBLIC METHODS                                                     */
        /* ------------------------------------------------------------------ */
        void makeSound(void) const;
};

#endif
